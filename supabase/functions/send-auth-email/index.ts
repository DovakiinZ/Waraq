/**
 * Supabase Edge Function: send-auth-email
 *
 * Supabase Auth "Send Email Hook". With the hook enabled, Supabase stops
 * sending its own auth emails and POSTs every one here instead: signup
 * verification, password reset, magic link, invite, email change and
 * reauthentication. We render a branded bilingual email and send it through
 * Resend (see `../_shared/email.ts`).
 *
 * Both clients benefit with no code change: the web app
 * (`AuthContext.signUp` / `resetPassword`) and the Flutter app
 * (`auth_repository.dart`) keep calling supabase-js/supabase-dart as before.
 *
 * ── Secrets ─────────────────────────────────────────────────────────────────
 *   SEND_EMAIL_HOOK_SECRET  `v1,whsec_…`, generated by the dashboard when the
 *                           hook is created (Auth → Hooks → Send Email).
 *   + RESEND_API_KEY / EMAIL_FROM / SITE_URL (see _shared/email.ts)
 *
 * ── Deploy ──────────────────────────────────────────────────────────────────
 *   supabase functions deploy send-auth-email --no-verify-jwt
 *
 * No JWT: the caller is Supabase Auth itself. Every request is authenticated
 * by its Standard Webhooks signature instead, verified below.
 *
 * ── Failure mode ────────────────────────────────────────────────────────────
 * A non-2xx here makes the originating auth call (signUp, resetPasswordForEmail)
 * fail with the message we return, so the user sees an error instead of
 * waiting for an email that is never coming.
 */

import { Webhook } from "https://esm.sh/standardwebhooks@1.0.0";
import { EmailContent, render, sendEmail } from "../_shared/email.ts";

const SUPABASE_URL = Deno.env.get("SUPABASE_URL")!;
const HOOK_SECRET = (Deno.env.get("SEND_EMAIL_HOOK_SECRET") ?? "").replace(
  /^v1,whsec_/,
  "",
);

type ActionType =
  | "signup"
  | "recovery"
  | "invite"
  | "magiclink"
  | "email_change"
  | "email"
  | "reauthentication";

interface HookPayload {
  user: {
    id: string;
    email: string;
    new_email?: string;
    user_metadata?: { full_name?: string };
  };
  email_data: {
    token: string;
    token_hash: string;
    redirect_to: string;
    email_action_type: ActionType;
    site_url: string;
    token_new: string;
    token_hash_new: string;
  };
}

function fail(status: number, message: string): Response {
  return new Response(
    JSON.stringify({ error: { http_code: status, message } }),
    { status, headers: { "Content-Type": "application/json" } },
  );
}

function verifyUrl(tokenHash: string, type: string, redirectTo: string): string {
  const u = new URL(`${SUPABASE_URL}/auth/v1/verify`);
  u.searchParams.set("token", tokenHash);
  u.searchParams.set("type", type);
  if (redirectTo) u.searchParams.set("redirect_to", redirectTo);
  return u.toString();
}

function greeting(name: string | undefined, lang: "ar" | "en"): string {
  const n = (name ?? "").trim();
  if (lang === "ar") return n ? `مرحباً ${n}،` : "مرحباً،";
  return n ? `Hi ${n},` : "Hi,";
}

const IGNORE_AR = "إن لم تطلب ذلك فتجاهل هذه الرسالة، ولن يتغيّر شيء في حسابك.";
const IGNORE_EN = "If you didn't ask for this, ignore this email — nothing about your account changes.";

