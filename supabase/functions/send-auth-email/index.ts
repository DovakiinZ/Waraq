Deno.serve(async (req) => {
  if (req.method !== "POST") return fail(405, "Method not allowed");
  if (!HOOK_SECRET) return fail(500, "SEND_EMAIL_HOOK_SECRET is not set");

  const raw = await req.text();
  let payload: HookPayload;
  try {
    payload = new Webhook(HOOK_SECRET).verify(
      raw,
      Object.fromEntries(req.headers),
    ) as HookPayload;
  } catch {
    return fail(401, "Invalid webhook signature");
  }

  const { user, email_data: d } = payload;
  const name = user.user_metadata?.full_name;
  const type = d.email_action_type;
  const redirectTo = d.redirect_to || d.site_url;

  try {
    const jobs: Promise<string>[] = [];

    if (type === "email_change" && d.token_hash_new) {
      // Secure email change: both addresses must confirm. Per the Supabase hook
      // contract, token_hash_new pairs with the CURRENT address and token_hash
      // with the NEW one (the naming is historical).
      const toCurrent = render(build(type, name, verifyUrl(d.token_hash_new, type, redirectTo), d.token));
      const toNew = render(build(type, name, verifyUrl(d.token_hash, type, redirectTo), d.token_new));
      jobs.push(sendEmail({ to: user.email, ...toCurrent, idempotencyKey: `auth-${d.token_hash_new}`, tags: [{ name: "type", value: "auth_email_change" }] }));
      if (user.new_email) {
        jobs.push(sendEmail({ to: user.new_email, ...toNew, idempotencyKey: `auth-${d.token_hash}`, tags: [{ name: "type", value: "auth_email_change" }] }));
      }
    } else {
      const to = type === "email_change" && user.new_email ? user.new_email : user.email;
      const content = build(type, name, verifyUrl(d.token_hash, type, redirectTo), d.token);
      if (!content) return fail(400, `Unsupported email_action_type: ${type}`);
      jobs.push(sendEmail({
        to,
        ...render(content),
        idempotencyKey: `auth-${d.token_hash || d.token}`,
        tags: [{ name: "type", value: content.tag }],
      }));
    }

    await Promise.all(jobs);
    return new Response("{}", { status: 200, headers: { "Content-Type": "application/json" } });
  } catch (err) {
    console.error("send-auth-email failed", type, err);
    return fail(500, err instanceof Error ? err.message : "Email send failed");
  }
});
